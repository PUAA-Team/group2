def acceptance_by_usecase():
    """从验收表展开用例范围，避免逐项对应表再次维护一套模块映射。"""
    result = {}
    for aid, covered, _, _ in ACCEPTANCE:
        package = None
        for match in re.finditer(r"(?:([A-Z]+)-)?(\d{2})(?:～(\d{2}))?", covered):
            package = match.group(1) or package
            if package is None:
                raise ValueError(f"验收用例缺少包名：{covered}")
            start = int(match.group(2))
            end = int(match.group(3) or start)
            for number in range(start, end + 1):
                uid = f"UC-{package}-{number:02d}"
                result.setdefault(uid, []).append(aid)
    return {uid: "、".join(ids) for uid, ids in result.items()}


