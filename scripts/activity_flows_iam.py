"""用户、数据和基础资产用例的活动流程；仅表达原规约中的业务路径。"""


def flow(identifier, title, actor, node_lines, edge_lines, basic, alternatives):
    nodes = []
    for line in node_lines.strip().splitlines():
        key, kind, col, row, text = line.split('|', 4)
        nodes.append(dict(key=key, kind=kind, col=int(col), row=float(row), text=text.replace('/', '\n')))
    edges = []
    for line in edge_lines.strip().splitlines():
        parts = line.split('|')
        source, target = parts[0].split('>')
        edge = dict(from_=source, to=target)
        edge['from'] = edge.pop('from_')
        if len(parts) > 1 and parts[1]:
            edge['guard'] = parts[1]
        edges.append(edge)
    return dict(id=identifier, title=title, actor=actor, nodes=nodes, edges=edges,
                coverage=dict(basic=[str(i) for i in range(1, basic + 1)],
                              alternatives=alternatives.split(',')))


def validated(identifier, title, actor, entry, input_text, check, success, error, basic, alternatives):
    return flow(identifier, title, actor, f"""
s|initial|0|0|
open|action|0|1|{entry}
input|action|0|2|{input_text}
check|action|1|2|{check}
valid|decision|1|3|校验结果
save|action|1|4.5|{success}
error|action|2|3|{error}
retry|action|0|4.5|修正后重试
show|action|1|5.5|展示结果/及可用状态
end|final|1|6.5|
""", """
s>open
open>input
input>check
check>valid
valid>save|通过
valid>error|不通过
error>retry
retry>input
save>show
show>end
""", basic, alternatives)


